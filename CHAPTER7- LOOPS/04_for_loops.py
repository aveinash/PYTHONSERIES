# a for loops is used to iterate through a sequence like list, tuple, or string(iterable)

s = "python"   # for loop with string
for i in s:
    print(i)
print("        ")

# for loop with tuple
t = {"hello",True,33,22,}
for i in t:
    print(i)
print("    ")

# for loop in list
l = [12,"two",23,32,1]
for i in l:
    print(i)
else:
    print("done")  # for loop with else used when the loop exhausts!